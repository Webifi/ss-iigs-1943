"""The generated sources and the link inputs of the Second Sight program.

The asset builder writes its sources into build/secondsight/gen with
generate() and asset(). write_inputs() writes the rest that "make
secondsight" reads: the list of generated sources (sources.mk), the places
for the fitter (fit.txt, scripts/secondsight_fit.py), the values of the
asset builder (defines.ld) and the window values of asset labels
(formulas.ld) for src/secondsight/secondsight.ld.

fixed() reads the places of src/secondsight/fixed.ld from a link of that file
alone (build/secondsight/fixed.elf): the asset builder needs them before the
link.
"""

import elf32

from roms import ROOT

OUT = ROOT / "build/secondsight"
GENERATED = OUT / "gen"
_generated = []  # names of the generated sources of this build
_defines = {}  # values that the asset builder computes, for the link
_aliases = {}  # layout symbol -> linker expression of asset labels
_later = []  # (name, function that returns a Source): sources made at the end
_fixed = {}  # load address -> byte: data at fixed places of the card memory map

# The places that the asset builder gives the fitter (build/secondsight/gen/fit.txt).
pinned = {}  # section name -> load address, for data at a place of the memory map
runs = {}  # plane section name -> run address (a number or a symbol), for code that runs elsewhere
free_vram = None  # function: the free video RAM ranges, read at the end


def fixed(name):
    """The value of symbol NAME of src/secondsight/fixed.ld."""
    return elf32.global_symbols(OUT / "fixed.elf")[name]


def generate(name, text):
    """Write build/secondsight/gen/NAME.s, the source "gen/NAME" of this build."""
    GENERATED.mkdir(parents=True, exist_ok=True)
    path = GENERATED / f"{name}.s"
    if not (path.exists() and path.read_text() == text):
        path.write_text(text)
    if name not in _generated:
        _generated.append(name)
    return f"gen/{name}"


def generate_include(name, text):
    """Write build/secondsight/gen/NAME.inc for `.include "NAME.inc"` in card sources."""
    path = GENERATED / f"{name}.inc"
    if path.exists() and path.read_text() == text:
        return
    GENERATED.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def define(name, value):
    """Set the symbol NAME to a value of the asset builder in the link."""
    _defines[name] = value


def alias(name, expression):
    """Define the layout symbol NAME in the link as EXPRESSION of asset
    labels and derived symbols (asset_source)."""
    _defines.pop(name, None)
    _aliases[name] = expression


def asset(name, source):
    """Write an asset_source.Source as build/secondsight/gen/NAME.s. The memory map
    or the fitter places its sections."""
    return generate(name, source.text())


def asset_later(name, make):
    """Add the Source that MAKE returns to the link, after the build has
    added every part of it."""
    _later.append((name, make))


def load(address, data):
    """DATA at card load ADDRESS (0x100000 + physical SRAM, or video RAM). The
    link places it there; a later load of the same byte wins."""
    for i, value in enumerate(bytes(data)):
        _fixed[address + i] = value


def _fixed_source():
    """One section for each run of fixed bytes, pinned at its address."""
    from asset_source import Source

    source = Source("data at fixed places of the card memory map")
    places = []
    for address in sorted(_fixed):
        if places and places[-1][0] + len(places[-1][1]) == address and address != 0x100000:
            places[-1][1].append(_fixed[address])
        else:
            places.append((address, bytearray((_fixed[address],))))
    for i, (address, data) in enumerate(places):
        name = f".fixed.{i}"
        pinned[name] = address
        source.section(name).data(data)
    return source


def write_inputs():
    """Write the last generated sources and the files that "make secondsight"
    reads besides the sources."""
    from asset_source import formulas

    for name, make in _later:
        asset(name, make())
    if _fixed:
        asset("fixed_loads", _fixed_source())
    names = " ".join(_generated)
    (GENERATED / "sources.mk").write_text(f"# Generated by scripts/secondsight_link.py.\nGENERATED := {names}\n")
    lines = ["# Generated by scripts/secondsight_link.py: the places that the asset builder gives the fitter."]
    lines += [f"pin {name} 0x{address:X}" for name, address in sorted(pinned.items())]
    lines += [f"run {name} {run if isinstance(run, str) else f'0x{run:X}'}" for name, run in sorted(runs.items())]
    lines += [f"vram 0x{lo:X} 0x{hi:X}" for lo, hi in (free_vram() if free_vram else [])]
    (GENERATED / "fit.txt").write_text("\n".join(lines) + "\n")
    (GENERATED / "defines.ld").write_text(
        "/* Generated by scripts/secondsight_link.py: values of the asset builder. */\n"
        + "".join(f"{name} = 0x{value:x};\n" for name, value in sorted(_defines.items()))
    )
    (GENERATED / "formulas.ld").write_text(
        "/* Generated by scripts/secondsight_link.py: layout symbols of the asset builder. */\n"
        + "".join(f"{name} = {expression};\n" for name, expression in sorted(_aliases.items()))
        + formulas()
    )
