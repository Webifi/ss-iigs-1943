"""Relative card data for the linker: generated assembly sources and the
derived symbols that the card linker script computes from their labels.

A Source holds bytes, labels and values. A value is a number or a symbol
expression that GNU as passes to ld as a relocation (a label, or a label plus
a constant). The asset builder never knows an address: card.ld places each
section, and the formulas below derive window and bank values from the
placed labels.

Address spaces of the labels (the VMA of the asset sections in card.ld):
  SRAM   0x100000 + physical card SRAM address
  VRAM   linear video RAM byte address, 0x000000-0x0FFFFF
  PLANE  0x200000 + plane * 0x40000 + group: bytes of one VGA plane
"""

SRAM = 0x100000
PLANE = 0x200000

# name -> (formula, description). {0} is the label.
FORMULAS = {
    # The bank area at $C000 maps physical BBR * 4 KB + $C000.
    "bbr": ("(((({0}) - 0x100000) >> 12) - 0x0C) & 0xFF", "BBR value that maps the label at $C000-$CFFF"),
    "ptr": ("0xC000 + (({0}) & 0xFFF)", "pointer to the label through the bank area"),
    # Common area 1 at $E000 maps physical CBR * 4 KB + $E000.
    "low16": ("({0}) & 0xFFFF", "the low 16 bits"),
    "phys": ("({0}) - 0x100000", "physical SRAM address of a load address"),
    # Compact glyph address: physical / 2.
    "half": ("(((({0}) - 0x100000) >> 1) & 0xFFFF)", "physical address of the label / 2"),
    "cbr": ("(((({0}) - 0x100000) >> 12) - 0x0E) & 0xFF", "CBR value that maps the label at $E000-$EFFF"),
    # Video RAM: 64 KB segments of four-byte groups, seen through 8 KB windows.
    "vseg": ("(({0}) >> 18) & 0xFF", "Oak segment of the group of the label"),
    "vbbr": ("0x94 + (((({0}) >> 2) & 0xFFFF) >> 13) * 2", "BBR value of the 8 KB VGA window of the label"),
    "vptr": ("0xC000 + ((({0}) >> 2) & 0x1FFF)", "window pointer to the group of the label"),
    "group": ("(({0}) >> 2) & 0x3FFFF", "group address of a linear video RAM label"),
    "group16": ("(({0}) >> 2) & 0xFFFF", "group address in its Oak segment"),
    "dma": ("0xA0000 + ((({0}) >> 2) & 0xFFFF)", "DMA address of the group through the VGA aperture"),
    "gb0": ("(({0}) >> 2) & 0xFF", "low byte of the group address"),
    "gb1": ("(({0}) >> 10) & 0xFF", "middle byte of the group address"),
    "vbbr4k": ("0x94 + (((({0}) >> 2) & 0xFFFF) >> 12)", "BBR value of the 4 KB VGA window of the label"),
    "vptr4k": ("0xC000 + ((({0}) >> 2) & 0xFFF)", "pointer to the label through its 4 KB VGA window"),
    # One VGA plane: the group is the low 18 bits.
    "pseg": ("(({0}) >> 16) & 0x03", "Oak segment of a plane label"),
    "pbbr": ("0x94 + ((({0}) & 0xFFFF) >> 13) * 2", "BBR value of the 8 KB VGA window of a plane label"),
    "pptr": ("0xC000 + (({0}) & 0x1FFF)", "window pointer to a plane label"),
    "plane": ("(({0}) >> 18) & 0x03", "plane of a plane label"),
}

_derived = {}  # symbol -> (kind, label expression)


def derived(kind, label):
    """The symbol whose value is FORMULAS[kind] of LABEL (a label or a label
    plus a constant). card.ld includes the formula."""
    name = f"{_symbol(label)}__{kind}"
    previous = _derived.setdefault(name, (kind, label))
    assert previous == (kind, label), (name, previous, (kind, label))
    return name


def derive(name):
    """Register NAME when it has the form LABEL__KIND of a formula kind: a
    source can use the derived symbols of any label."""
    label, _, kind = name.rpartition("__")
    if label and kind in FORMULAS and name not in _derived:
        derived(kind, label)


def _symbol(expression):
    expression = expression.replace(" ", "").replace("+", "_p_").replace("-", "_m_")
    return "".join(ch if ch.isalnum() or ch == "_" else "_" for ch in expression)


def formulas():
    """The linker script text that defines every derived symbol."""
    return "".join(
        f"{name} = {FORMULAS[kind][0].format(label)};\n" for name, (kind, label) in sorted(_derived.items())
    )


class Source:
    """One generated assembly source of relative data.

    Bytes go into the current section. Labels are global symbols for card
    code and other assets.
    """

    def __init__(self, title):
        self.lines = [f"; Generated by the asset builder: {title}."]
        self.size = 0  # bytes in the current section

    def section(self, name, flags="a"):
        self.lines.append(f'        .section {name},"{flags}",@progbits')
        self.size = 0
        return self

    def label(self, name):
        self.lines += [f"        .global {name}", f"{name}:"]
        return self

    def byte(self, *values):
        self.lines.append("        .byte " + ", ".join(_value(v, 0xFF) for v in values))
        self.size += len(values)
        return self

    def word(self, *values):
        self.lines.append("        .word " + ", ".join(_value(v, 0xFFFF) for v in values))
        self.size += 2 * len(values)
        return self

    def data(self, data):
        data = bytes(data)
        for i in range(0, len(data), 16):
            self.lines.append("        .byte " + ", ".join(f"0x{v:02X}" for v in data[i : i + 16]))
        self.size += len(data)
        return self

    def fill(self, count, value=0):
        if count:
            self.lines.append(f"        .fill {count}, 1, {value}")
            self.size += count
        return self

    def code(self, lines):
        """Generated instructions; the caller counts their size."""
        self.lines += list(lines)
        return self

    def text(self):
        return "\n".join(self.lines) + "\n"


def _value(value, limit):
    if not isinstance(value, int):
        return str(value)
    assert -limit // 2 - 1 <= value <= limit, (value, limit)
    return f"0x{value & limit:X}"


class Records:
    """Small records for banked SRAM, each in its own .desc section: card.ld
    puts each one into the first 4 KB page with space, so no record crosses
    a window. Equal records share one label."""

    def __init__(self, name, title):
        self.name = name
        self.source = Source(title)
        self.labels = {}

    def add(self, key, fill):
        """The label of the record KEY; FILL(source) writes a new record."""
        if key not in self.labels:
            label = f"{self.name}_{len(self.labels)}"
            self.source.section(f".desc.{label}").code(["        .balign 2"]).label(label)
            fill(self.source)
            self.labels[key] = label
        return self.labels[key]

    def pointer(self, key, fill):
        """(BBR value, window pointer) symbols of the record KEY."""
        label = self.add(key, fill)
        return derived("bbr", label), derived("ptr", label)


class Pool:
    """Lists of bytes and words for common SRAM. The asset builder stores each
    byte once: a list that is a part of another list is a label inside it.
    A list holds byte values (int) and word symbols (str)."""

    def __init__(self, name, title):
        self.name = name
        self.title = title
        self.lists = {}

    def add(self, tokens):
        """The label of the list TOKENS."""
        tokens = tuple(tokens)
        if tokens not in self.lists:
            self.lists[tokens] = f"{self.name}_{len(self.lists)}"
        return self.lists[tokens]

    def source(self):
        """One .common section for each list that is not a part of another."""
        containers = []  # (tokens, {position: [labels]})
        for tokens in sorted(self.lists, key=len, reverse=True):
            for whole, members in containers:
                at = next(
                    (i for i in range(len(whole) - len(tokens) + 1) if whole[i : i + len(tokens)] == tokens),
                    None,
                )
                if at is not None:
                    members.setdefault(at, []).append(self.lists[tokens])
                    break
            else:
                containers.append((tokens, {0: [self.lists[tokens]]}))
        source = Source(self.title)
        for i, (tokens, members) in enumerate(containers):
            source.section(f".common.{self.name}_{i}")
            for at, token in enumerate(tokens):
                for label in members.get(at, []):
                    source.label(label)
                if isinstance(token, str):
                    source.word(token)
                else:
                    source.byte(token)
        return source


class Vram:
    """A video RAM group address: a label of a linear video RAM section plus
    a number of groups (four bytes, one in each plane)."""

    def __init__(self, label, groups=0):
        self.label = label
        self.groups = groups

    def __add__(self, groups):
        return Vram(self.label, self.groups + groups)

    __radd__ = __add__

    def __sub__(self, groups):
        return Vram(self.label, self.groups - groups)

    def expression(self):
        """The linear address as a linker expression."""
        offset = 4 * self.groups
        return self.label if not offset else f"{self.label} {'+' if offset > 0 else '-'} {abs(offset)}"

    def __call__(self, kind):
        """The derived symbol KIND (FORMULAS) of this address."""
        return derived(kind, self.expression())

    def value(self):
        """The group address, after the final card link."""
        from card_link import symbol

        return (symbol(self.label) >> 2) + self.groups

    def plane(self, plane, groups=0):
        """The address of byte GROUPS of PLANE inside this block, in the
        plane address space."""
        return Plane(self.label, plane, self.groups + groups)


class Plane:
    """An address in one VGA plane: PLANE + plane * 0x40000 + group. A plane
    section of a video RAM block has its labels in this space."""

    def __init__(self, label, plane, groups=0):
        self.label = label
        self.plane = plane
        self.groups = groups

    def value(self):
        """The group address, after the final card link."""
        from card_link import symbol

        return (symbol(self.label) & 0x3FFFF) + self.groups

    def __call__(self, kind):
        """The derived symbol KIND (FORMULAS) of this address."""
        return derived(kind, self.label if not self.groups else f"{self.label} + {self.groups}")


class VideoRam:
    """The video RAM sections of the asset builder. scripts/card_layout.py
    places each one so that it stays inside one window of WINDOW groups.
    A rule of a section is its window, its alignment in bytes (ALIGN) and the
    groups at the start of each 64K-group segment that it keeps out of (KEEP).
    """

    def __init__(self):
        self.parts = []  # (label, rule, mode, payload)
        self.shared = {}
        self.pins = {}  # label -> (linear address, content bytearray or size)

    def pin(self, label, address, content):
        """A section at a place of the video RAM map (scripts/card_layout.py
        pinned): CONTENT loads there at boot, or a size loads nothing."""
        self.pins[label] = (address, content)

    def _label(self, name):
        return name or f"vram_{len(self.parts)}"

    def add(self, data, window=0x4000, share=True, name=None, align=4, keep=0):
        """A section of the bytes DATA; equal bytes share one section."""
        data = bytes(data)
        rule = f"b{window}_a{align}_k{keep}"
        if share and not name and (data, rule) in self.shared:
            return Vram(self.shared[data, rule])
        label = self._label(name)
        self.parts.append((label, rule, "data", data))
        if share and not name:
            self.shared[data, rule] = label
        return Vram(label)

    def reserve(self, size, window=0x4000, fill=None, name=None):
        """SIZE bytes that FILL() makes at link time, or that no load writes
        (FILL None: the card clears or fills them at run time)."""
        label = self._label(name)
        self.parts.append((label, f"b{window}_a4_k0", "nobits" if fill is None else "fill", (size, fill)))
        return Vram(label)

    def block(self, groups, window, name):
        """A block of GROUPS groups whose bytes are plane sections: section
        .plane.NAME.P.K is the K-th part of plane P. scripts/card_layout.py
        places the block, then the parts of each plane in order from the
        block's first group."""
        self.parts.append((name, f"b{window}_a4_k0", "nobits", (groups * 4, None)))
        return Vram(name)

    def table(self, size, write, window=0x4000, name=None):
        """SIZE bytes that WRITE(source) writes at link time, with symbols."""
        label = self._label(name)
        self.parts.append((label, f"b{window}_a4_k0", "write", (size, write)))
        return Vram(label)

    def source(self):
        import card_layout

        source = Source("video RAM data")
        for label, (address, content) in self.pins.items():
            name = f".vram_area.{label}"
            card_layout.pinned[name] = address
            if isinstance(content, int):
                source.lines.append(f'        .section {name},"aw",@nobits')
                source.label(label)
                source.lines.append(f"        .skip {content}")
            else:
                source.section(name).label(label).data(content)
        for label, rule, mode, payload in self.parts:
            name = f".vram.{rule}.{label}"
            if mode == "nobits":
                size, _ = payload
                source.lines.append(f'        .section {name},"aw",@nobits')
                source.label(label)
                source.lines.append(f"        .skip {size}")
                continue
            source.section(name).label(label)
            if mode == "data":
                source.data(payload)
                continue
            size, make = payload
            start = source.size
            if mode == "fill":
                source.data(make())
            else:
                make(source)
            assert source.size - start == size, (label, source.size - start, size)
        return source
