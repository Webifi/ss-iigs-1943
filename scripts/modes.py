"""Raw Z180 mode programming. Counts are explicit, not firmware mode names."""

class Registers:
    """The register records of a mode: (0 OUT or 1 IN, port, value)."""

    def __init__(self):
        self.records = []

    def write(self, port, value):
        self.records.append((0, port, value))

    def read(self, port):
        self.records.append((1, port, 0))

    def indexed(self, port, index, value):
        self.write(port, index)
        self.write(port + 1, value)


def apply_table(records, alternate=None, prefix="mode"):
    """Generate the mode table program PREFIX (src/card/include/mode_table.inc)
    as build/card/gen/PREFIX.s.

    With ALTERNATE (the RGB records), only the bytes that differ are stored,
    as replacements applied before the table runs.
    """
    from card_link import generate

    original = bytes(v for op, port, value in records for v in (op, port & 255, port >> 8, value))
    patches = []
    if alternate is not None:
        replacement = bytes(
            v for op, port, value in alternate for v in (op, port & 255, port >> 8, value)
        )
        assert len(original) == len(replacement)
        patches = [(i, v) for i, v in enumerate(replacement) if v != original[i]]
        assert 0 < len(patches) < 256
    lines = [
        "; Generated by scripts/modes.py: video mode register table.",
        '        .include "mode_table.inc"',
        '        .section .text.mode_table,"ax",@progbits',
        f"        .global {prefix}, {prefix}_data, {prefix}_done",
        f"{prefix}:",
        f"        mode_table {prefix}, {len(patches)}",
        f"{prefix}_data:",
        *(
            f"        .byte {op}, 0x{port & 255:02X}, 0x{port >> 8:02X}, 0x{value:02X}"
            for op, port, value in records
        ),
        "        .byte 0xFF",
    ]
    if patches:
        lines.append(f"{prefix}_rgb:")
        lines += [f"        .byte 0x{value:02X}\n        .word {prefix}_data + {offset}" for offset, value in patches]
    lines.append(f"{prefix}_done:")
    generate(prefix, "\n".join(lines) + "\n")


