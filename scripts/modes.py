def mode_data(mode, layout="packed", display_width=None):
    assert layout in ("packed", "unchained")
    c = Registers()
    m = dict(MODES[mode])
    w = m["width"]
    vt = m["total"] - 2
    vd = m["visible"] - 1
    vb = m["visible"] + m.get("vborder", 0)
    sync_lines = m.get("vsync_lines", 3 if m["rgb"] else 4)
    vs = vb + m.get("vfront", (m["total"] - vb - sync_lines) // 2)
    h = m["htotal"] // 8
    display = w * 2 // 8
    sync_chars = m.get("hsync_chars", (12) if m["rgb"] else 16)
    border = (m.get("monitor_width", w) - w) // 2
    assert border % 4 == 0
    # Active pixels begin at raster x=0. Right overscan follows the game;
    # left overscan is at the end of the preceding line, after blanking.
    # The monitor's visible window therefore wraps across raster x=0.
    hb = display + border // 4
    hbe = h - border // 4
    hs = hb + m.get("hfront", (hbe - hb - sync_chars) // 2)
    he = hs + sync_chars
    c.write(0xA9 if m["rgb"] else 0xA8, 0)  # the card pixel clock: RGB or VGA
    c.indexed(0x3C4, 0, 1)
    c.indexed(0x3C4, 1, 1)
    c.write(0x3C2, 0xE3 | ((m["clock"] & 3) << 2))
    # Bt481A Command A: four mask reads, then the command write. Explicit
    # indexed mode does not inherit the firmware's selected pixel format.
    c.read(0x3C7)
    for _ in range(4):
        c.read(0x3C6)
    c.write(0x3C6, 0)  # indexed pixels
    c.write(0x3C8, 0)
    c.write(0x3C6, 255)  # pixel mask
    c.indexed(0x3DE, 6, m["clock"])
    c.indexed(0x3DE, 0x21, 0)
    c.indexed(0x3DE, 0x20, 5)
    if layout == "unchained":
        # IBM VGA unchained 256-colour path. One address selects four pixels.
        c.indexed(0x3C4, 2, 15)
        c.indexed(0x3C4, 4, 6)
        for index, value in ((0, 0), (1, 0), (3, 0), (4, 0), (5, 0x40), (6, 5), (7, 15), (8, 255)):
            c.indexed(0x3CE, index, value)
        c.indexed(0x3DE, 0x22, 8)
        c.indexed(0x3DE, 0x30, 0)
        c.indexed(0x3DE, 0x23, 0)
        c.indexed(0x3DE, 0x24, 0)
    c.indexed(0x3DE, 0x14, 0)
    c.indexed(0x3DE, 0x15, 0)
    c.indexed(0x3DE, 0x18, 0)
    c.indexed(0x3DE, 0x17, 0)
    c.indexed(0x3D4, 0x11, 0x30)
    overflow = (
        ((vt >> 8) & 1)
        | (((vd >> 8) & 1) << 1)
        | (((vs >> 8) & 1) << 2)
        | (((vb >> 8) & 1) << 3)
        | 0x10
        | (((vt >> 9) & 1) << 5)
        | (((vd >> 9) & 1) << 6)
        | (((vs >> 9) & 1) << 7)
    )
    scan = (0x80 if m["double"] else 0) | 0x40 | (((vb >> 9) & 1) << 5)
    crtc = {
        0: h - 5,
        1: display - 1,
        2: hb,
        3: 0x80 | (hbe & 31),
        4: hs,
        5: (he & 31) | ((hbe & 32) << 2),
        6: vt & 255,
        7: overflow,
        8: 0,
        9: scan,
        0xA: 0x20,
        0xB: 0,
        0xC: 0,
        0xD: 0,
        0x10: vs & 255,
        0x11: 0x30 | ((vs + sync_lines) & 15),
        0x12: vd & 255,
        0x13: w // (8),
        0x14: 0,
        0x15: vb & 255,
        0x16: (m["total"] - 1 - m.get("vborder", 0)) & 255,
        0x17: 0xC3,
        0x18: 255,
    }
    for index, value in crtc.items():
        c.indexed(0x3D4, index, value)
    c.read(0x3DA)  # reset the attribute flip-flop
    for value in (0x30, 0x41, 0x31, 0):
        c.write(0x3C0, value)
    c.indexed(0x3C4, 0, 3)
    return dict(
        m,
        layout=layout,
        crtc=crtc,
        vertical_sync_start=vs,
        vertical_blank_lines=m["total"] - m["visible"],
        horizontal_front_porch=(hs - hb) * 8,
        horizontal_sync=sync_chars * 8,
        horizontal_back_porch=(hbe - he) * 8,
        border_positions_each_side=border,
        horizontal_blank_start=hb * 8,
        horizontal_blank_end=hbe * 8,
        monitor_window="last left-border positions of previous line, active game, right border",
        vertical_front_porch=vs - vb,
        vertical_sync=sync_lines,
        vertical_back_porch=m["total"] - m.get("vborder", 0) - vs - sync_lines,
        hsync_negative=not m.get("positive", False),
        vsync_negative=not m.get("positive", False),
        register_records=c.records,
        register_format="operation, port low, port high, value; FF terminates",
    )


def program(mode, layout="packed", display_width=None, auto_monitor=False, name="mode"):
    """The register table NAME_data of MODE."""
    if auto_monitor:
        # Shared register bytes are stored once. The RGB program replaces
        # only its differing data bytes before the ordinary table runs.
        mode = "vga-224x256-roomy"
    data = mode_data(mode, layout, display_width)
    rgb = mode_data("rgb-224x256-276", layout, display_width) if auto_monitor else None
    apply_table(data["register_records"], rgb["register_records"] if rgb else None, name)
    data["register_table_label"] = f"{name}_data"
    if rgb:
        data["monitor_selection"] = "Oak $3C2 bit 4: 1 VGA, 0 AppleColor RGB; startup only"
        data["rgb_mode"] = rgb
    return data
