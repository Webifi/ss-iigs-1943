"""Build and allocate the reversible Second Sight firmware-mirror transition."""

from iigs_payload import HostData


def allocate(host):
    """The menu mirror packets: the bootstrap packet and the two helpers
    (.mirror_bootstrap, .mirror_enter and .mirror_restore of secondsight.ld,
    src/secondsight/menu_mirror.s). The IIgs link puts in the linked bytes.
    These bytes are menu-owned for the entire game; only the snapshot
    contents change while gameplay is paused. The SRAM snapshot (bank $0F)
    and the 32 KiB video snapshot ($E0/$E1 language-card RAM) are areas of
    src/iigs.cfg (src/menu_mirror_host.s)."""
    # The bootstrap packet: its length word, the 66-byte header (byte 27 is
    # 127), then the bootstrap, padded to an even length. The menu code swaps
    # the bytes of each word while it copies the packet for the PEI transport.
    header = bytearray(66)
    header[27] = 127
    wire = HostData().word("MIRROR_PACKET_END-MIRROR_PACKET-2").data(header).linked_bytes("mirror_bootstrap")
    host.blob_at(wire, "MIRROR_PACKET", length="MIRROR_PACKET_BYTES")
    host.blob_at(HostData().linked_bytes("mirror_enter"), "MIRROR_ENTER", length="MIRROR_ENTER_BYTES")
    host.blob_at(HostData().linked_bytes("mirror_restore"), "MIRROR_RESTORE", length="MIRROR_RESTORE_BYTES")
    (host.out / "menu-mirror.inc").write_text(
        "; Generated by scripts/menu_mirror.py: the payload of the bootstrap packet.\n"
        "MIRROR_PAYLOAD_BYTES = MIRROR_PACKET_BYTES-2\n"
    )
