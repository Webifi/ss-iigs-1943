"""Resident two-player HUD layouts. The wire carries values, not glyph lists."""

from roms import load

BOSS_TEMPLATE = None


def glyphs(kind, color):
    if kind == "game_line" and color == 1:
        return [(0x24, 0), (0x71, 1), (0x72, 1), (0x73, 1)]
    if kind == "score2":
        return [(i, color) for i in (*range(10), 0x24)]
    if kind == "loop":
        return [(0x24, 0), (27, 0)]
    return (
        [(i, 0) for i in range(37)]
        + [(i, color) for i in range(0x80, 0x89)]
        + [(ord(ch) - 55, 8) for ch in "GAMEOVER"]
    )


def prepare(scene, pool, chars, energy):
    global BOSS_TEMPLATE
    variables = {}
    for i, cell in energy.items():
        variables[i] = ("game_line", cell, 2)
    for player, color in ((0, 2), (1, 0)):
        for cell in range(8 if player == 0 else 0, 14):
            variables[len(chars)] = ("game_line", player * 14 + cell, color)
            chars.append(("char", 0, 0x24, 0, 0, 8, player * 112 + cell * 8))
    for cell in range(8):
        variables[len(chars)] = ("score2", cell, 0)
        chars.append(("char", 0, 0x24, 0, 0, 240, 112 + cell * 8))
    for cell, code in enumerate((2, 30, 25)):
        chars.append(("char", 0, code, 0, 0, 248, 112 + cell * 8))
    for cell in range(8):
        variables[len(chars)] = (f"p2_weapon_name{cell}", 0, 0)
        chars.append(("char", 0, 0x24, 0, 0, 0, 120 + cell * 8))
    for cell in range(2):
        variables[len(chars)] = ("p2_weapon_time", cell, 7)
        chars.append(("char", 0, 0x24, 7, 0, 0, 200 + cell * 8))
    # Shared loop stock, drawn as original R glyphs below the high score.
    for cell in range(4):
        variables[len(chars)] = ("loop", cell, 0)
        chars.append(("char", 0, 0x24, 0, 0, 240, 96 + cell * 8))
    BOSS_TEMPLATE = 0xC000 + 10 * (8 + len(set(variables) | set(scene.weapon_characters)))
    # ROM $AC97-$ACC3: five four-cell bars, in upright row 32.
    for cell in range(20):
        variables[len(chars)] = ("game_line", 28 + cell, 1)
        chars.append(("char", 0, 0x24, 0, 0, 216, 56 + cell * 8))
    scene.game_characters = variables
    for kind, _, color in variables.values():
        if kind.startswith("p2_weapon"):
            from weapon_hud import glyphs as weapon_glyphs

            choices = weapon_glyphs(kind[3:])
        else:
            choices = glyphs(kind, color)
        for code, palette in choices:
            pool.get(("char", 0, code, palette, 0, 0, 0))
    for cmd in chars:
        pool.get(cmd)
    from hud_fast import damage_spans

    scene.hud_spans = damage_spans(scene, pool, chars, energy)


def messages_source():
    """build/secondsight/gen/game_hud_messages.s."""
    from secondsight_link import generate

    assert BOSS_TEMPLATE is not None
    # The UI messages of the ROM (CONTINUE, GAME OVER, ...) as HUD selectors.
    r = load()[0]["maincpu"]
    lines = [
        "; Generated by scripts/game_hud.py from the ROM: HUD selectors of the UI messages.",
        '        .section .rodata.game_hud_messages,"a",@progbits',
        "        .global game_hud_messages",
        "game_hud_messages:",
    ]
    for pointer in (0x1F50, 0x1F72, 0x1F0C, 0x1F2E, None):
        codes = [36] * 14
        if pointer:
            for i, v in enumerate(r[pointer + 5 : pointer + 17]):
                if pointer == 0x1F2E and v != 36:
                    v = 46 + "GAMEOVER".index(chr(v + 55))
                codes[i + 1] = v if v < 54 else 36
        lines.append("        .byte " + ", ".join(str(v) for v in codes))
    generate("game_hud_messages", "\n".join(lines) + "\n")
